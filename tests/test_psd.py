class TestSegmentExtraction:
    """Validate extract_segments under various overlap and length configurations."""

    def test_zero_overlap(self):
        x = np.arange(100, dtype=np.float64)
        segs = extract_segments(x, segment_length=20, overlap_samples=0)
        assert segs.shape == (5, 20)
        for m in range(5):
            np.testing.assert_array_equal(segs[m], x[m * 20 : (m + 1) * 20])

    def test_50_percent_overlap(self):
        x = np.arange(100, dtype=np.float64)
        segs = extract_segments(x, segment_length=20, overlap_samples=10)
        # Hop is 10. Segments start at 0, 10, 20, 30, 40, 50, 60, 70, 80 (9 segments, last ends at 100)
        assert segs.shape == (9, 20)
        for m in range(9):
            np.testing.assert_array_equal(segs[m], x[m * 10 : m * 10 + 20])

    def test_non_divisible_trailing_data_discarded(self):
        # 105 samples, segment=20, overlap=10 -> still 9 segments, 5 trailing samples discarded
        x = np.arange(105, dtype=np.float64)
        segs = extract_segments(x, segment_length=20, overlap_samples=10)
        assert segs.shape == (9, 20)

    def test_segment_length_equals_data_length(self):
        x = np.arange(32, dtype=np.float64)
        segs = extract_segments(x, segment_length=32, overlap_samples=0)
        assert segs.shape == (1, 32)
        np.testing.assert_array_equal(segs[0], x)

    def test_segment_length_exceeds_data_length_raises(self):
        x = np.arange(32, dtype=np.float64)
        with pytest.raises(ValueError, match="cannot exceed input data length"):
            extract_segments(x, segment_length=64, overlap_samples=0)

    def test_invalid_overlap_raises(self):
        x = np.arange(64, dtype=np.float64)
        with pytest.raises(ValueError, match="0 <= overlap_samples < segment_length"):
            extract_segments(x, segment_length=16, overlap_samples=-1)
        with pytest.raises(ValueError, match="0 <= overlap_samples < segment_length"):
            extract_segments(x, segment_length=16, overlap_samples=16)


