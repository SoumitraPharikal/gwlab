class TestSingleSegmentConsistency:
    """Verify single-segment PSD consistency with Stage 1.1 conventions."""

    def test_unwindowed_matches_stage_1_1_periodogram(self):
        rng = np.random.default_rng(42)
        M = 512
        delta_t = 1.0 / 2048.0
        x = rng.normal(0.0, 1.0, size=M)

        # 1. Unwindowed single_segment_psd with None
        psd_none = single_segment_psd(x, delta_t, window=None)
        # 2. Unwindowed single_segment_psd with all ones
        psd_ones = single_segment_psd(x, delta_t, window=np.ones(M))
        # 3. Stage 1.1 one_sided_periodogram
        psd_stage11 = one_sided_periodogram(x, delta_t)

        np.testing.assert_allclose(psd_none, psd_stage11, rtol=1e-14)
        np.testing.assert_allclose(psd_ones, psd_stage11, rtol=1e-14)

    def test_single_segment_welch_matches_single_segment_psd(self):
        rng = np.random.default_rng(101)
        M = 256
        delta_t = 1.0 / 1024.0
        x = rng.normal(0.0, 1.0, size=M)

        # Welch PSD with segment_length = M and zero overlap
        _, psd_welch = welch_psd(x, delta_t, segment_length=M, overlap_samples=0, window="tukey")
        w = tukey_window(M, alpha=0.25)
        psd_single = single_segment_psd(x, delta_t, window=w)

        np.testing.assert_allclose(psd_welch, psd_single, rtol=1e-14)

    def test_windowed_parseval_expectation(self):
        """Verify that sum(S(f) * df) equals sum(w^2 x^2) / (M * S_2)."""
        rng = np.random.default_rng(202)
        M = 1024
        delta_t = 1.0 / 4096.0
        delta_f = 1.0 / (M * delta_t)
        x = rng.normal(0.0, 2.5, size=M)
        w = tukey_window(M, alpha=0.25)

        psd = single_segment_psd(x, delta_t, window=w)
        freq_integral = np.sum(psd) * delta_f

        s2 = window_power(w)
        time_mean_square = np.sum((w * x) ** 2) / (M * s2)

        assert freq_integral == pytest.approx(time_mean_square, rel=1e-12)


