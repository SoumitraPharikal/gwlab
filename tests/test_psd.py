class TestWhiteNoisePSD:
    """Verify that ensemble-averaged Welch PSD matches theoretical expectation."""

    def test_welch_mean_ensemble_white_noise(self):
        f_s = 4096.0
        delta_t = 1.0 / f_s
        M = 256
        sigma = 1.5
        n_realizations = 300

        expected_interior = expected_white_noise_psd(sigma, delta_t, bin_type="interior")
        expected_dc = expected_white_noise_psd(sigma, delta_t, bin_type="dc")
        expected_nyquist = expected_white_noise_psd(sigma, delta_t, bin_type="nyquist")

        rng = np.random.default_rng(12345)
        n_samples = 1024

        psd_sum = np.zeros(M // 2 + 1, dtype=np.float64)
        for _ in range(n_realizations):
            x = rng.normal(0.0, sigma, size=n_samples)
            _, psd = welch_psd(x, delta_t, segment_length=M, overlap_samples=M // 2, window="tukey")
            psd_sum += psd

        psd_mean = psd_sum / n_realizations

        # Interior bins: mean over 10 <= k <= M/2 - 10
        interior_measured = np.mean(psd_mean[10:-10])
        assert interior_measured == pytest.approx(expected_interior, rel=0.04)

        # DC and Nyquist check (factor of 2 lower)
        assert psd_mean[0] == pytest.approx(expected_dc, rel=0.15)
        assert psd_mean[-1] == pytest.approx(expected_nyquist, rel=0.15)


