class TestFrequencyGrid:
    """Validate frequency grid properties generated by welch_psd."""

    def test_frequency_grid_properties(self):
        f_s = 4096.0
        delta_t = 1.0 / f_s
        M = 1024
        x = np.zeros(2048, dtype=np.float64)

        freqs, psd = welch_psd(x, delta_t=delta_t, segment_length=M)

        # Expected bins: M // 2 + 1
        expected_n_freqs = M // 2 + 1
        assert freqs.shape == (expected_n_freqs,)
        assert psd.shape == (expected_n_freqs,)

        # Endpoints
        assert freqs[0] == pytest.approx(0.0, abs=1e-12)
        assert freqs[-1] == pytest.approx(f_s / 2.0, rel=1e-9)

        # Spacing
        delta_f = 1.0 / (M * delta_t)
        np.testing.assert_allclose(np.diff(freqs), delta_f, rtol=1e-12)

    def test_consistency_with_stage_1_1_grid(self):
        delta_t = 1.0 / 2048.0
        M = 512
        x = np.zeros(1024, dtype=np.float64)

        freqs_welch, _ = welch_psd(x, delta_t=delta_t, segment_length=M)
        freqs_expected = build_frequency_grid(M, delta_t)

        np.testing.assert_allclose(freqs_welch, freqs_expected, rtol=1e-14)


