class TestInputValidation:
    """Ensure comprehensive error handling for all invalid inputs."""

    def test_reject_complex_input(self):
        x_c = np.ones(256, dtype=np.complex128)
        with pytest.raises(ValueError, match="must be real-valued"):
            welch_psd(x_c, delta_t=1.0, segment_length=64)

    def test_reject_non_finite_input(self):
        x_nan = np.zeros(256)
        x_nan[10] = float("nan")
        with pytest.raises(ValueError, match="must contain only finite numbers"):
            welch_psd(x_nan, delta_t=1.0, segment_length=64)

        x_inf = np.zeros(256)
        x_inf[10] = float("inf")
        with pytest.raises(ValueError, match="must contain only finite numbers"):
            welch_psd(x_inf, delta_t=1.0, segment_length=64)

    def test_reject_invalid_delta_t(self):
        x = np.zeros(256)
        for bad_dt in [0.0, -1.0, float("nan"), float("inf"), "1.0"]:
            with pytest.raises(ValueError, match="delta_t must be a positive finite float"):
                welch_psd(x, delta_t=bad_dt, segment_length=64)

    def test_reject_invalid_segment_length(self):
        x = np.zeros(256)
        with pytest.raises(ValueError, match="segment_length must be a positive integer"):
            welch_psd(x, delta_t=1.0, segment_length=0)
        with pytest.raises(ValueError, match="segment_length must be an even integer"):
            welch_psd(x, delta_t=1.0, segment_length=63)
        with pytest.raises(ValueError, match="cannot exceed input data length"):
            welch_psd(x, delta_t=1.0, segment_length=512)

    def test_reject_invalid_method(self):
        x = np.zeros(256)
        with pytest.raises(ValueError, match="method must be either 'mean' or 'median'"):
            welch_psd(x, delta_t=1.0, segment_length=64, method="maximum")  # type: ignore

    def test_reject_invalid_method_parameter_combinations(self):
        x = np.zeros(256)
        # Passing bias_correct to method="mean"
        with pytest.raises(ValueError, match="bias_correct and assume_independent_exponential_periodograms are only applicable when method='median'"):
            welch_psd(x, delta_t=1.0, segment_length=64, method="mean", bias_correct=True)

        # Setting assertion to True when bias_correct is False
        with pytest.raises(ValueError, match="assume_independent_exponential_periodograms was set to True, but bias_correct is False"):
            welch_psd(x, delta_t=1.0, segment_length=64, method="median", bias_correct=False, assume_independent_exponential_periodograms=True)

    def test_reject_invalid_window_type_and_size(self):
        x = np.zeros(256)
        with pytest.raises(ValueError, match="Unknown window string 'hamming'"):
            welch_psd(x, delta_t=1.0, segment_length=64, window="hamming")
        with pytest.raises(ValueError, match="Custom window length \\(32\\) must match segment_length \\(64\\)"):
            welch_psd(x, delta_t=1.0, segment_length=64, window=np.ones(32))
        with pytest.raises(TypeError, match="window must be a str, np.ndarray, or None"):
            welch_psd(x, delta_t=1.0, segment_length=64, window=123)  # type: ignore


