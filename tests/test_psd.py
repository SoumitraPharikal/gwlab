class TestWindowNormalization:
    """Validate discrete Tukey window formulas, power, coherent gain, and overlap correlation."""

    def test_baseline_tukey_quantities(self):
        """Verify M = 32,768, alpha = 0.25 discrete values against Stage 0.6 derivations."""
        M = 32768
        alpha = 0.25
        w = tukey_window(M, alpha=alpha)

        assert w.shape == (M,)
        assert w.dtype == np.float64

        # Exact symmetry w_j == w_{M - 1 - j}
        np.testing.assert_allclose(w, w[::-1], atol=1e-15)

        # Power normalization S_2
        s2 = window_power(w)
        assert s2 == pytest.approx(27.0 / 32.0, rel=1e-7)

        # Coherent gain S_1
        s1 = window_coherent_gain(w)
        assert s1 == pytest.approx(7.0 / 8.0, rel=1e-7)

        # 50% overlap correlation r_w
        rw = window_overlap_correlation(w, overlap_samples=M // 2)
        assert rw == pytest.approx(4.0 / 9.0, rel=1e-7)

    @pytest.mark.parametrize("alpha,expected_s2", [
        (0.0, 1.0),            # Rectangular
        (0.25, 27.0 / 32.0),   # Stage 0 baseline
        (1.0, 3.0 / 8.0),      # Hann window asymptotic
    ])
    def test_tukey_alpha_extremes(self, alpha: float, expected_s2: float):
        M = 4096
        w = tukey_window(M, alpha=alpha)
        s2 = window_power(w)
        assert s2 == pytest.approx(expected_s2, rel=1e-4)

    def test_short_segment_lengths(self):
        for M in [4, 8, 16, 64]:
            w = tukey_window(M, alpha=0.25)
            assert len(w) == M
            assert np.all(np.isfinite(w))
            assert np.all(w >= 0.0)
            assert np.all(w <= 1.0)
            # Midpoint symmetry preserved
            np.testing.assert_allclose(w, w[::-1], atol=1e-15)

    def test_zero_overlap_correlation(self):
        w = tukey_window(128, alpha=0.25)
        rw_zero = window_overlap_correlation(w, overlap_samples=0)
        assert rw_zero == 0.0

    def test_invalid_window_parameters(self):
        with pytest.raises(ValueError, match="length must be a positive integer"):
            tukey_window(0)
        with pytest.raises(ValueError, match="length must be an even integer"):
            tukey_window(15)
        with pytest.raises(ValueError, match="alpha must be a finite float between 0.0 and 1.0"):
            tukey_window(64, alpha=-0.1)
        with pytest.raises(ValueError, match="alpha must be a finite float between 0.0 and 1.0"):
            tukey_window(64, alpha=1.1)
        with pytest.raises(ValueError, match="alpha must be a finite float between 0.0 and 1.0"):
            tukey_window(64, alpha=float("nan"))


